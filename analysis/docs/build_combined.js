const {
  Document, Packer, Paragraph, TextRun, HeadingLevel, Table, TableRow, TableCell,
  WidthType, ShadingType, AlignmentType, VerticalAlign
} = require("docx");

const FONT = "游明朝";
const HFONT = "游ゴシック";

function p(text) {
  return new Paragraph({
    spacing: { after: 200, line: 360 },
    children: [new TextRun({ text, font: FONT, size: 21 })],
  });
}

function heading(text, level) {
  const sizes = { [HeadingLevel.HEADING_1]: 28, [HeadingLevel.HEADING_2]: 24 };
  return new Paragraph({
    heading: level,
    spacing: { before: 320, after: 160 },
    children: [new TextRun({ text, font: HFONT, bold: true, size: sizes[level] || 23 })],
  });
}

function tableCaption(text) {
  return new Paragraph({
    spacing: { before: 100, after: 100 },
    children: [new TextRun({ text, font: FONT, size: 19, bold: true })],
  });
}

function cell(text, opts = {}) {
  return new TableCell({
    width: { size: opts.width, type: WidthType.DXA },
    shading: opts.shade ? { type: ShadingType.CLEAR, color: "auto", fill: opts.shade } : undefined,
    verticalAlign: VerticalAlign.CENTER,
    margins: { top: 90, bottom: 90, left: 110, right: 110 },
    children: [new Paragraph({
      alignment: opts.center ? AlignmentType.CENTER : AlignmentType.LEFT,
      children: [new TextRun({ text, font: FONT, size: opts.size || 19, bold: !!opts.bold })],
    })],
  });
}

function makeTable(colW, headerTexts, rows, favorableIdx) {
  const tableWidth = colW.reduce((a, b) => a + b, 0);
  const header = new TableRow({
    tableHeader: true,
    children: headerTexts.map((t, i) => cell(t, { width: colW[i], shade: "21295C", bold: true, center: true })),
  });
  const body = rows.map((r, idx) => new TableRow({
    children: r.map((t, i) => cell(t, {
      width: colW[i],
      shade: favorableIdx && favorableIdx.has(idx) ? "EAF7F0" : (idx % 2 === 0 ? "F4F7F9" : undefined),
    })),
  }));
  return new Table({ width: { size: tableWidth, type: WidthType.DXA }, columnWidths: colW, rows: [header, ...body] });
}

